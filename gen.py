#!/usr/bin/env python3
"""Generate a Docker deployment for one chain profile.

Writes deploy/<chain>/ with
  peers.txt            all addresses, read by every node
  tc/<region>.sh       egress shaping for a node in <region>: one netem delay per destination region
  docker-compose.yml   one container per validator, plus the client and the provider

Validators are spread over regions by a weight column of config/regions.csv (sources in
config/regions.md). Delays come from config/owd.csv (source in its header). Each region gets its own
/22 of 10.100.0.0/16, so one u32 filter per region selects the delay towards it.
"""

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PORT = 7000


def read_csv(name):
    with open(ROOT / "config" / name) as f:
        return list(csv.DictReader(l for l in f if not l.startswith("#")))


def spread(n, weights):
    """Largest-remainder split of n validators over regions."""
    total = sum(weights.values())
    exact = {r: n * w / total for r, w in weights.items()}
    counts = {r: int(x) for r, x in exact.items()}
    for r in sorted(exact, key=lambda r: exact[r] - counts[r], reverse=True)[: n - sum(counts.values())]:
        counts[r] += 1
    return counts


def ip(k, j):
    """Address j in region k: 10.100.(4k + j // 240).(10 + j % 240)."""
    return f"10.100.{4 * k + j // 240}.{10 + j % 240}"


def tc_script(src, regions, owd, jitter):
    lines = [
        "#!/bin/sh",
        f"# Egress shaping for a node in {src}. The one-way delay is applied on the sender's side.",
        "set -e",
        'BW="${BW:-1gbit}"',
        "tc qdisc add dev eth0 root handle 1: htb default 99 r2q 10000",
        "tc class add dev eth0 parent 1: classid 1:1 htb rate $BW",
        "tc class add dev eth0 parent 1:1 classid 1:99 htb rate $BW",
    ]
    for k, dst in enumerate(regions):
        d = owd[src][dst]
        jit = f" {jitter}ms distribution normal" if jitter > 0 else ""
        c = 10 + k
        lines += [
            f"# to {dst}",
            f"tc class add dev eth0 parent 1:1 classid 1:{c} htb rate $BW",
            f"tc qdisc add dev eth0 parent 1:{c} handle {c}: netem delay {d}ms{jit} limit 1000000",
            f"tc filter add dev eth0 parent 1: protocol ip prio 1 u32 match ip dst 10.100.{4 * k}.0/22 flowid 1:{c}",
        ]
    return "\n".join(lines) + "\n"


def service(name, role, region, addr, extra=""):
    return f"""  {name}:
    <<: *node
    command: ["{role}"]
    environment:
      <<: *env
      REGION: {region}{extra}
    networks:
      sim:
        ipv4_address: {addr}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("chain")
    ap.add_argument("--weights", default="eth", help="weight column of config/regions.csv (eth or sol)")
    ap.add_argument("--client-region", default="eu-central-1")
    ap.add_argument("--provider-region", default="us-east-1")
    ap.add_argument("--jitter-ms", type=float, default=0, help="netem jitter, reorders packets if > 0")
    ap.add_argument("--n", type=int, help="override the chain's validator count")
    args = ap.parse_args()

    chain = {c["name"]: c for c in read_csv("chains.csv")}[args.chain]
    n = args.n or int(chain["n"])
    weights = {r["region"]: float(r[args.weights]) for r in read_csv("regions.csv")}
    regions = list(weights)
    owd = {row["from"]: row for row in read_csv("owd.csv")}
    counts = spread(n, weights)

    out = ROOT / "deploy" / args.chain
    (out / "tc").mkdir(parents=True, exist_ok=True)
    (out / "results").mkdir(exist_ok=True)

    nodes = []  # (service, role, region, ip)
    for k, r in enumerate(regions):
        for j in range(counts[r]):
            nodes.append((f"v{len(nodes)}", "validator", r, ip(k, j)))
    for name, r, j in [("client", args.client_region, 950), ("provider", args.provider_region, 951)]:
        nodes.append((name, name, r, ip(regions.index(r), j)))

    with open(out / "peers.txt", "w") as f:
        f.writelines(f"{role} {addr}:{PORT}\n" for _, role, _, addr in nodes)
    for r in regions:
        (out / "tc" / f"{r}.sh").write_text(tc_script(r, regions, owd, args.jitter_ms))

    compose = f"""# Generated by gen.py for {args.chain}: {n} validators {counts}
name: fastsim-{args.chain}
x-env: &env
  PEERS: /config/peers.txt
  RESULTS: /results
  NETEM: ${{NETEM:-1}}
  BW: ${{BW:-1gbit}}
  WORKERS: ${{WORKERS:-1}}
  OPTION: ${{OPTION:-A}}
  TASKS: ${{TASKS:-200}}
  CONCURRENCY: ${{CONCURRENCY:-1}}
  WARMUP_S: ${{WARMUP_S:-5}}
  Y_BYTES: ${{Y_BYTES:-4096}}
  PROOF_BYTES: ${{PROOF_BYTES:-8192}}
  FORWARD: ${{FORWARD:-1}}
x-node: &node
  image: ${{IMAGE:-fastsim}}
  cap_add: [NET_ADMIN]
  volumes:
    - ./:/config:ro
    - ./results:/results
networks:
  sim:
    driver: bridge
    ipam:
      config:
        - subnet: 10.100.0.0/16
services:
"""
    for i, (name, role, r, addr) in enumerate(nodes):
        compose += service(name, role, r, addr, f'\n      ID: "{i}"' if role == "validator" else "")
    (out / "docker-compose.yml").write_text(compose)
    print(f"{args.chain}: {n} validators, {args.weights} weights {({r: c for r, c in counts.items() if c})} -> {out}")


if __name__ == "__main__":
    main()